@pytest.mark.parametrize("t", sorted(MDS), ids=[f"t{t}" for t in MDS])
def test_mds_property_over_official_fields(t):
    # Checking the minors directly over GF(p) takes minutes for t = 7, 8 (12869
    # 255-bit determinants), so check them over ZZ instead: by Hadamard's bound
    # every minor of every order is at most the product of the row norms (each
    # factor >= 1, so this also bounds all submatrix minors), which stays far
    # below both official primes -- hence a nonzero integer minor is nonzero
    # mod p, and MDS over ZZ implies MDS over both fields.
    from math import isqrt
    minor_bound = 1
    for row in MDS[t]:
        minor_bound *= isqrt(sum(x * x for x in row)) + 1
    assert minor_bound < min(BLS12_381_SCALAR.p, BN254_SCALAR.p)
    assert is_mds(MDS[t])   # integer entries, no field: minors over ZZ


