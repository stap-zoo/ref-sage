def test_low_addition_mds_search():
    M = low_addition_mds_matrix(3, 8, seed=42)
    assert is_mds(M, field=GF(P_BLS12))
    assert M == low_addition_mds_matrix(3, 8, seed=42)   # seeded -> reproducible
    with pytest.raises(ValueError):
        low_addition_mds_matrix(5, 12)   # below the t + ceil(t/2) + t gate minimum


def test_low_addition_mds_search_reaches_paper_budget_t5():
    # The published t = 5..8 matrices come from unseeded runs and cannot be
    # regenerated, but the search strategy must be able to hit the paper's
    # addition budgets (Table 4). For t = 5 the budget (13 additions) equals the
    # structural minimum and a succeeding seed is quick to find; seed 659 is one.
    M = low_addition_mds_matrix(5, 13, seed=659, attempts=1)
    assert is_mds(M, field=GF(P_BLS12))
    assert M == low_addition_mds_matrix(5, 13, seed=659, attempts=1)


# Seeded runs at relaxed budgets for the larger state sizes: the success
# probability at the paper's exact Table 4 budgets (t=6: 17, t=7: 24, t=8: 31)
# is so low that reaching them needs tens of thousands of restarts (the authors
# ran open-ended searches) -- not CI material. A few gates of slack over the
# t + ceil(t/2) + t structural minimum makes seeded runs succeed in milliseconds.
SEARCH_CASES = [
    # (t, additions, seed) -- each seed succeeds on its first attempt
    (6, 21, 3),
    (7, 28, 98),
    (8, 40, 62),
]


@pytest.mark.parametrize("t,additions,seed", SEARCH_CASES, ids=[f"t{t}-add{a}" for t, a, _ in SEARCH_CASES])
def test_low_addition_mds_search_slack_budgets(t, additions, seed):
    M = low_addition_mds_matrix(t, additions, seed=seed, attempts=1)
    # Integer-mode is_mds (minors over ZZ, as for the pinned MDS constants): the
    # field-mode check on a t=8 matrix over a 255-bit prime takes minutes, and
    # no ZZ-nonzero minor of these small entries can be divisible by such a p.
    assert is_mds(M)


def test_init_mat_fallback_warns_and_is_mds():
    # No published matrix exists for t = 2; _init_mat falls back to the randomized
    # low-addition search and flags that the result is not a published constant.
    # _init_mat's budget-escalation loop (additions += t on failure) never fires
    # here: at t = 2 the starting budget (2t + ceil(t/2) + t = 7) succeeds on
    # every attempt -- escalation only matters for larger t, where the success
    # probability at the starting budget collapses (e.g. t = 8 typically
    # escalates twice before finding a matrix).
    with pytest.warns(ParamRecommendationWarning):
        params = PolocoloParams(p=113, t=2, m=16, R=3, r=1, c=1, d=1, kappa=ceil(log2(113))*2, toy=True) # capacity/digest holds 2*kappa bits
    assert is_mds(params.M)


