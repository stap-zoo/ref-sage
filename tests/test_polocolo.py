def _eval_constraint_program(t: int, program: str, outputs: str) -> list[list[int]]:
    """Evaluate a straight-line program on the unit vectors, i.e. extract the matrix
    each output variable computes."""
    env = {f"x{i + 1}": [int(i == j) for j in range(t)] for i in range(t)}
    for stmt in program.split(";"):
        lhs, rhs = stmt.split("=")
        vec = [0] * t
        for term in rhs.split("+"):
            coeff, _, var = term.strip().rpartition("*")
            coeff = int(coeff) if coeff else 1
            vec = [a + coeff * b for a, b in zip(vec, env[var.strip()])]
        env[lhs.strip()] = vec
    return [env[o.strip()] for o in outputs.split(",")]


