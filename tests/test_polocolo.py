def _reference_input(label: str, t: int) -> list[int]:
    """The fixed inputs the reference vectors were generated on, by label."""
    if label == "counting":
        return list(range(t))
    if label == "zeros":
        return [0] * t
    if label == "negative":
        return [-(i + 1) for i in range(t)]
    raise ValueError(label)


